"""Tier 4 Real-World Scenario: Customer Master Deduplication & Consolidation.

Scenario Description:
An SMB CRM export contains dirty duplicate customer accounts created by different sales reps.
Duplicate customer profiles have typographical errors in company names, alternate email domains,
and varying legal suffixes. Crucially, multiple independent businesses frequently share the
same commercial office building address or phone prefix.

Acceptance Verification:
1. Star/Pivot clustering groups true customer duplicate profiles into cohesive master entities.
2. Distinct businesses with common prefixes or shared locations are protected from transitive merge.
3. String customer identifiers (e.g. 'CUST-0001-1') are processed without runtime errors.
"""

from __future__ import annotations

from typing import Any

from ..conftest import require_feature
from ..fixtures.customer_benchmark import generate_customer_benchmark


def test_scenario_customer_deduplication() -> Any:
    """Full workflow: Deduplicate customer CRM records using Star/Pivot clustering."""
    star_cluster_cls = require_feature(
        "fuzzymatch.clustering.star_cluster", "StarClusterer", milestone="M1"
    )

    _df_customers, ground_truth_clusters = generate_customer_benchmark(
        n_canonical=30,
        duplicate_ratio=0.60,
        seed=303,
    )

    # Build affinity graph between duplicate profiles
    # In a full run, this is generated by candidate blocker + scorer
    pairs: list[tuple[str, str]] = []
    weights: list[float] = []

    # True pairs have high affinity
    for member_ids in ground_truth_clusters.values():
        members = sorted(member_ids)
        for i in range(len(members)):
            for j in range(i + 1, len(members)):
                pairs.append((members[i], members[j]))
                weights.append(0.90)

    # Add a confusing edge between distinct businesses sharing a common word or location
    all_canon_ids = list(ground_truth_clusters.keys())
    dist_a = min(ground_truth_clusters[all_canon_ids[0]])
    dist_b = min(ground_truth_clusters[all_canon_ids[1]])
    dist_c = min(ground_truth_clusters[all_canon_ids[2]])

    # Intransitive triad between distinct customers: A-B has edge 0.72, B-C has edge 0.75, but A-C is 0.30
    pairs.append((dist_a, dist_b))
    weights.append(0.72)
    pairs.append((dist_b, dist_c))
    weights.append(0.75)
    pairs.append((dist_a, dist_c))
    weights.append(0.30)

    clusterer = star_cluster_cls(cutoff=0.70, verify_clique=True)
    clusters = clusterer.cluster(pairs, edge_weights=weights)

    # 1. Verify all true duplicate sets are preserved together
    for member_ids in ground_truth_clusters.values():
        if len(member_ids) > 1:
            # Find the cluster containing the first member
            first_m = min(member_ids)
            found_cluster = next((c for c in clusters if first_m in c), None)
            assert found_cluster is not None, f"Customer {first_m} was not clustered"
            for m in member_ids:
                assert m in found_cluster, f"Member {m} was split from cluster of {first_m}"

    # 2. Verify dist_a and dist_c were NOT collapsed together despite dist_b bridging them
    cl_a = next(c for c in clusters if dist_a in c)
    cl_c = next(c for c in clusters if dist_c in c)
    assert cl_a != cl_c, (
        f"Transitive false chaining merged distinct customer entities: {dist_a} and {dist_c}"
    )
